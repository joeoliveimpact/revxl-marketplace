/* The Grade Board tune maths, JavaScript side. Every constant comes from grade_math.json.
 *
 * Two consumers, one file:
 *   - the page, for the slider table and for the GLSL it compiles (glsl() writes the shader
 *     functions with these same numbers baked in, so the shader cannot drift from the bake);
 *   - node, for selftest_math.py, which pushes 200 random colours through here and through
 *     grade_math.py and fails if they differ by more than 1e-5.
 *
 * Do not put a number in here. Put it in grade_math.json.
 *
 * Browser:  <script src="grade_math.js"></script> then GradeMath.init(await fetch(json))
 * Node:     const GM = require('./grade_math.js'); GM.init(require('./grade_math.json'));
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.GradeMath = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  let SPEC = null, K = null;

  function init(spec) { SPEC = spec; K = spec.constants; return API; }
  function spec() { return SPEC; }
  function defaults(names) { const o = {}; for (const n of names) o[n] = SPEC.ranges[n][3]; return o; }

  const wrap360 = h => h - 360 * Math.floor(h / 360);
  const wrap180 = d => d - 360 * Math.floor((d + 180) / 360);
  const clamp01 = x => x < 0 ? 0 : x > 1 ? 1 : x;

  function rgbToHsv(r, g, b) {
    const mx = Math.max(r, g, b), mn = Math.min(r, g, b), d = mx - mn;
    const v = mx, s = mx > 0 ? d / mx : 0;
    let h;
    // branch order is r, then g, then b - grade_math.py replicates this chain with np.where
    if (d > 0) {
      if (mx === r) h = 60 * ((g - b) / d);
      else if (mx === g) h = 60 * ((b - r) / d + 2);
      else h = 60 * ((r - g) / d + 4);
      if (h < 0) h += 360;
    } else h = 0;
    return [h, s, v];
  }

  function hsvToRgb(h, s, v) {
    const c = v * s;
    let hh = h / 60; hh = hh - 6 * Math.floor(hh / 6);
    const x = c * (1 - Math.abs(hh - 2 * Math.floor(hh / 2) - 1));
    const m = v - c;
    const i = Math.min(5, Math.max(0, Math.floor(hh)));
    const r = [c, x, 0, 0, x, c][i], g = [x, c, c, x, 0, 0][i], b = [0, 0, x, c, c, x][i];
    return [r + m, g + m, b + m];
  }

  /* exposure -> levels -> clamp -> hue-selective skin rotation -> clamp */
  function prePass(rgb, p) {
    const gain = Math.pow(2, p.exposure), span = Math.max(p.white - p.black, K.levels_eps);
    let c = rgb.map(x => clamp01((x * gain - p.black) / span));
    const hsv = rgbToHsv(c[0], c[1], c[2]);
    const d = wrap180(hsv[0] - p.skin_hue);
    const t = Math.min(Math.abs(d) / Math.max(p.skin_band, 1e-6), 1);
    const w = 1 - t * t * (3 - 2 * t);
    const h = wrap360(hsv[0] + p.skin_rot * w);
    return hsvToRgb(h, hsv[1], hsv[2]).map(clamp01);
  }

  /* temp -> tint -> contrast -> saturation -> matte -> clamp. Takes the already-mixed colour. */
  function slotTune(rgb, t) {
    const temp = t.temp || 0, tint = t.tint || 0, con = t.con || 0, sat = t.sat || 0, mat = t.mat || 0;
    let r = rgb[0] + temp * K.temp_r, g = rgb[1], b = rgb[2] - temp * K.temp_b;
    r -= tint * K.tint_rb; g += tint * K.tint_g; b -= tint * K.tint_rb;
    const cg = 1 + con * K.contrast_gain, piv = K.contrast_pivot;
    r = (r - piv) * cg + piv; g = (g - piv) * cg + piv; b = (b - piv) * cg + piv;
    const l = r * K.luma_r + g * K.luma_g + b * K.luma_b, sg = 1 + sat * K.sat_gain;
    r = l + (r - l) * sg; g = l + (g - l) * sg; b = l + (b - l) * sg;
    const m = mat * K.matte_max;
    return [r * (1 - m) + m, g * (1 - m) + m, b * (1 - m) + m].map(clamp01);
  }

  /* mix (lerp identity -> LUT) then the tune */
  function applySlot(rgb, lutRgb, t) {
    const a = t.mix === undefined ? 1 : t.mix;
    return slotTune([0, 1, 2].map(i => rgb[i] + (lutRgb[i] - rgb[i]) * a), t);
  }

  /* ---- GLSL, generated from the same constants ------------------------------------------- */
  const f = x => { const s = String(x); return /[.eE]/.test(s) ? s : s + '.0'; };

  function glsl() {
    return `
// generated by grade_math.js from grade_math.json v${SPEC.version} - do not hand-edit in the page
const float GM_TEMP_R = ${f(K.temp_r)};
const float GM_TEMP_B = ${f(K.temp_b)};
const float GM_TINT_G = ${f(K.tint_g)};
const float GM_TINT_RB = ${f(K.tint_rb)};
const float GM_PIVOT = ${f(K.contrast_pivot)};
const float GM_CON_GAIN = ${f(K.contrast_gain)};
const float GM_SAT_GAIN = ${f(K.sat_gain)};
const vec3  GM_LUMA = vec3(${f(K.luma_r)}, ${f(K.luma_g)}, ${f(K.luma_b)});
const float GM_MATTE_MAX = ${f(K.matte_max)};
const float GM_EPS = ${f(K.levels_eps)};

float gm_wrap360(float h){ return h - 360.0 * floor(h / 360.0); }
float gm_wrap180(float d){ return d - 360.0 * floor((d + 180.0) / 360.0); }

vec3 gm_rgb2hsv(vec3 c){
  float mx = max(max(c.r, c.g), c.b);
  float mn = min(min(c.r, c.g), c.b);
  float d = mx - mn;
  float v = mx;
  float s = mx > 0.0 ? d / mx : 0.0;
  float h = 0.0;
  if (d > 0.0){
    if (mx == c.r) h = 60.0 * ((c.g - c.b) / d);
    else if (mx == c.g) h = 60.0 * ((c.b - c.r) / d + 2.0);
    else h = 60.0 * ((c.r - c.g) / d + 4.0);
    if (h < 0.0) h += 360.0;
  }
  return vec3(h, s, v);
}

vec3 gm_hsv2rgb(float h, float s, float v){
  float c = v * s;
  float hh = h / 60.0; hh = hh - 6.0 * floor(hh / 6.0);
  float x = c * (1.0 - abs(hh - 2.0 * floor(hh / 2.0) - 1.0));
  float m = v - c;
  int i = int(clamp(floor(hh), 0.0, 5.0));
  vec3 o;
  if (i == 0) o = vec3(c, x, 0.0);
  else if (i == 1) o = vec3(x, c, 0.0);
  else if (i == 2) o = vec3(0.0, c, x);
  else if (i == 3) o = vec3(0.0, x, c);
  else if (i == 4) o = vec3(x, 0.0, c);
  else o = vec3(c, 0.0, x);
  return o + m;
}

// exposure -> levels -> clamp -> hue-selective skin rotation -> clamp
vec3 gm_prePass(vec3 c, float exposure, float black, float white, float skinHue, float skinRot, float skinBand){
  c = c * pow(2.0, exposure);
  c = (c - black) / max(white - black, GM_EPS);
  c = clamp(c, 0.0, 1.0);
  vec3 hsv = gm_rgb2hsv(c);
  float d = gm_wrap180(hsv.x - skinHue);
  float t = min(abs(d) / max(skinBand, 1e-6), 1.0);
  float w = 1.0 - t * t * (3.0 - 2.0 * t);
  float h = gm_wrap360(hsv.x + skinRot * w);
  return clamp(gm_hsv2rgb(h, hsv.y, hsv.z), 0.0, 1.0);
}

// temp -> tint -> contrast -> saturation -> matte -> clamp
vec3 gm_slotTune(vec3 c, float temp, float tint, float con, float sat, float mat){
  c += vec3(temp * GM_TEMP_R, 0.0, -temp * GM_TEMP_B);
  c += vec3(-tint * GM_TINT_RB, tint * GM_TINT_G, -tint * GM_TINT_RB);
  c = (c - GM_PIVOT) * (1.0 + con * GM_CON_GAIN) + GM_PIVOT;
  float l = dot(c, GM_LUMA);
  c = l + (c - l) * (1.0 + sat * GM_SAT_GAIN);
  float m = mat * GM_MATTE_MAX;
  c = c * (1.0 - m) + m;
  return clamp(c, 0.0, 1.0);
}

// mix (lerp identity -> LUT) then the tune. tune = [mix, temp, tint, con, sat, mat]
vec3 gm_applySlot(vec3 c, vec3 lut, float mixAmt, float temp, float tint, float con, float sat, float mat){
  return gm_slotTune(c + (lut - c) * mixAmt, temp, tint, con, sat, mat);
}
`;
  }

  const API = { init, spec, defaults, rgbToHsv, hsvToRgb, prePass, slotTune, applySlot, glsl };
  return API;
});
